fun toArabicNumerals(n: Int): String {
    val arabicDigits = charArrayOf('٠','١','٢','٣','٤','٥','٦','٧','٨','٩')
    return n.toString().map { if (it.isDigit()) arabicDigits[it - '0'] else it }.joinToString("")
}

fun getHizbForPage(pageNumber: Int): Int {
    val entry = QuranQuartersMap.filterKeys { it <= pageNumber }.maxByOrNull { it.key }
    return entry?.value?.hizb ?: 1
}


