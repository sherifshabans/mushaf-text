package io.github.sherifshabans.mushaf

/**
 * The 240 Madinah quarters and the 15 sajdah positions, as page-margin marks.
 *
 * The table is the sample app's `QuranQuartersMap` with one correction:
 * quarter 106 is **15:49**, where `hafs.tsv` carries the `۞`, not 15:50.
 * The in-line glyph is the authority: every quarter whose ayah is not 1
 * starts with `۞` in the text, and every `۞` is exactly one quarter.
 * A quarter on ayah 1 of a surah has no star (the surah banner owns the
 * line) and is known only from this table.
 *
 * `juz` follows the hizb structure (`(hizb + 1) / 2`): hizb 21 is the first
 * hizb of juz 11, so 9:93 starts juz 11. `hafs.tsv`'s own juz column calls
 * 9:93 juz 10 — a source quirk; this table follows the glyph and the printed
 * division structure, like the star positions do.
 */
enum class DivisionKind { JUZ, HIZB, RUB, NISF, THREE_QUARTERS, SAJDAH }

/**
 * One division (or sajdah) starting on [page].
 *
 * @property kind what the margin medallion announces.
 * @property page the page the ayah is printed on (1‥604).
 * @property surah surah number (1‥114).
 * @property ayah ayah number within the surah.
 * @property hizb 1‥60; 0 for a lone sajdah.
 * @property juz 1‥30.
 * @property quarterIndex 1‥240; 0 for a sajdah.
 */
data class MushafMark(
    val kind: DivisionKind,
    val page: Int,
    val surah: Int,
    val ayah: Int,
    val hizb: Int,
    val juz: Int,
    val quarterIndex: Int,
) {
    /** Short Arabic label drawn inside the margin medallion. */
    val labelArabic: String
        get() = when (kind) {
            DivisionKind.JUZ -> "جزء"
            DivisionKind.HIZB -> "حزب"
            DivisionKind.RUB -> "ربع"
            DivisionKind.NISF -> "نصف"
            DivisionKind.THREE_QUARTERS -> "ثلاثة"
            DivisionKind.SAJDAH -> "سجدة"
        }
}

/** A quarter row: `index, hizb, part (0 = hizb start, 1 = rubʿ, 2 = nisf, 3 = three-quarters)`. */
private fun q(index: Int, hizb: Int, part: Int, surah: Int, ayah: Int, page: Int) = MushafMark(
    kind = when (part) {
        0 -> if (hizb % 2 == 1) DivisionKind.JUZ else DivisionKind.HIZB
        1 -> DivisionKind.RUB
        2 -> DivisionKind.NISF
        else -> DivisionKind.THREE_QUARTERS
    },
    page = page,
    surah = surah,
    ayah = ayah,
    hizb = hizb,
    juz = (hizb + 1) / 2,
    quarterIndex = index,
)

/** A sajdah row. */
private fun s(surah: Int, ayah: Int, page: Int, juz: Int) = MushafMark(
    kind = DivisionKind.SAJDAH,
    page = page,
    surah = surah,
    ayah = ayah,
    hizb = 0,
    juz = juz,
    quarterIndex = 0,
)

